"""Frozen: runs against `prometheus/elo.py` at commit 00237c0 (options since removed).


elo_experience.py: does experience matter after the rookie window?

The published rookie discount (a player counts 200 points lower in their first
game, fading linearly to nothing over 50 games, never stored in their rating) stops
at 50 games. Residual checks on the replayed Elo (2026-10-12) found a team's mean
career games still predicting results beyond Elo (z +3.1 within other leagues, +3.4
across leagues), and 400+ game veterans in other leagues doing worse (z −2.5). This
replays Elo (`elo_variants.replay`) with three designs, each tuned on seasons up to
2021 and reported on 2022 onwards against the published Elo on the same games:

- **Log discount** (`rookie_curve="log"`): the discount falls with log(1 + games),
  D × (1 − log(1 + g) / log(1 + N)), so it drops fast early and lasts longer.
- **Log discount + veteran (games)**: the best log discount plus a late-career
  discount growing from 0 at G games to P at 2G (`veteran_games`,
  `veteran_penalty`), never stored, like the rookie one.
- **Log discount + veteran (years)**: the same, from Y years after the player's
  first game to P three years later (`veteran_years`).

The faster early moves (×2 for 25 games) stay on throughout. Tuning objective,
fixed in advance: mean Elo log loss over domestic (major-league) and
within-other-league games up to 2021, games-weighted (as `elo_new_players.py`).
Held-out sections (2022 on): domestic and international Elo and FORGE, within other
leagues Elo on per-league curves and FORGE, and cross-league Elo.

Usage:
    VECLIB_MAXIMUM_THREADS=1 uv run python scripts/research/elo_experience.py --out docs/research/elo_experience.md
"""

import argparse
import datetime
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import elo_new_players as enp
import elo_variants as ev
import evaluate_metrics as em

TRAIN_LAST = 2021
LOG_GRID = [
    {"rookie_curve": "log", "rookie_penalty": d, "rookie_games": n}
    for d in (150, 200, 250)
    for n in (50, 100, 200, 400)
]
VETERAN_GAMES_GRID = [
    {"veteran_games": g, "veteran_penalty": p}
    for g in (300, 500, 800)
    for p in (25, 50, 100)
]
VETERAN_YEARS_GRID = [
    {"veteran_years": y, "veteran_penalty": p} for y in (4, 6, 8) for p in (25, 50, 100)
]


def tune(inputs, pairs, margin, grid, train, base=None, label=""):
    """Train objective of every params in `grid` on top of `base`; best first."""
    scored = []
    for params in grid:
        full = {**(base or {}), **params}
        pre = ev.replay(inputs, margin, **full)
        scored.append((enp.objective(inputs, pairs, pre, train), full))
        print(f"  {label} {full}: {scored[-1][0]:.5f}", flush=True)
    return min(scored, key=lambda t: t[0])


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out", type=Path)
    args = ap.parse_args()

    inputs = ev.load_inputs(verbose=False)
    pairs = em.load_pair_games()
    years = sorted(inputs.frame["year"].unique())
    train = [y for y in years if y <= TRAIN_LAST]
    test = [y for y in years if y > TRAIN_LAST]
    margin = ev.game_length_margin()
    base_pre = ev.replay(inputs, margin)  # published Elo

    base_obj = enp.objective(inputs, pairs, base_pre, train)
    chosen = {}
    obj, best_log = tune(inputs, pairs, margin, LOG_GRID, train, label="log")
    chosen["Log discount"] = (best_log, obj)
    obj, best = tune(
        inputs, pairs, margin, VETERAN_GAMES_GRID, train, best_log, "games"
    )
    chosen["Log discount + veteran (games)"] = (best, obj)
    obj, best = tune(
        inputs, pairs, margin, VETERAN_YEARS_GRID, train, best_log, "years"
    )
    chosen["Log discount + veteran (years)"] = (best, obj)

    lines = [
        f"## Experience past the rookie window ({datetime.date.today().isoformat()})\n",
        "Generated by `scripts/research/elo_experience.py`. Tuned on "
        f"{train[0]}–{train[-1]} (objective: mean Elo log loss over domestic and "
        f"within-other-league games), reported on {test[0]}–{test[-1]}. Δ is variant "
        "minus published Elo (rookie discount 200 over 50 games, linear; moves ×2 for "
        "25 games) log loss (negative is better), paired bootstrap over games.\n",
        "### Tuning\n",
        "| Design | Best parameters | Train objective | Published |",
        "|---|---|---:|---:|",
    ]
    for design, (params, obj) in chosen.items():
        lines.append(f"| {design} | {params} | {obj:.5f} | {base_obj:.5f} |")

    base_scores = ev.score(inputs, base_pre, years=test)
    base_other_g, base_other = enp.other_losses(pairs, base_pre, test)
    base_cross_g, base_cross = enp.cross_losses(pairs, base_pre, test)
    base_of_g, base_of = enp.other_forge_losses(inputs, pairs, base_pre, test)
    lines += [
        "\n### Held out\n",
        "| Design | Elo, domestic | Elo, international | FORGE, domestic "
        "| FORGE, international | Elo, other leagues | FORGE, other leagues "
        "| Elo, cross-league |",
        "|---|---|---|---|---|---|---|---|",
        f"| Published (log loss) | {base_scores.log_loss('elo_live', 'Domestic').mean():.4f} "
        f"| {base_scores.log_loss('elo_live', 'International').mean():.4f} "
        f"| {base_scores.log_loss('forge', 'Domestic').mean():.4f} "
        f"| {base_scores.log_loss('forge', 'International').mean():.4f} "
        f"| {base_other.mean():.4f} | {base_of.mean():.4f} | {base_cross.mean():.4f} |",
    ]
    counts = (
        f"Games: domestic {int(base_scores.mask('Domestic').sum()):,}, international "
        f"{int(base_scores.mask('International').sum()):,}, other leagues "
        f"{len(base_other_g):,} (FORGE {len(base_of_g):,}), cross-league "
        f"{len(base_cross_g):,}."
    )
    for design, (params, _) in chosen.items():
        pre = ev.replay(inputs, margin, **params)
        s = ev.score(inputs, pre, years=test)
        oth_g, oth = enp.other_losses(pairs, pre, test)
        cr_g, cr = enp.cross_losses(pairs, pre, test)
        of_g, of = enp.other_forge_losses(inputs, pairs, pre, test)
        assert len(oth_g) == len(base_other_g) and len(cr_g) == len(base_cross_g)
        assert len(of_g) == len(base_of_g)
        cells = [
            enp._delta(s.log_loss(m, t), base_scores.log_loss(m, t))
            for m, t in (
                ("elo_live", "Domestic"),
                ("elo_live", "International"),
                ("forge", "Domestic"),
                ("forge", "International"),
            )
        ] + [
            enp._delta(oth, base_other),
            enp._delta(of, base_of),
            enp._delta(cr, base_cross),
        ]
        lines.append(f"| {design} {params} | " + " | ".join(cells) + " |")
    lines.append(f"\n{counts}\n")
    text = "\n".join(lines) + "\n"
    print(text)
    if args.out:
        args.out.write_text(text)


if __name__ == "__main__":
    main()
