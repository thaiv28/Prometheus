"""
elo_k_tier.py: should Elo react faster, and by how much in each tier?

A team's Elo change over its last 10 games predicts its next result beyond Elo
(z +8.9 within other leagues, +2.7 in the majors, in sample; still there without
players under 50 games), so ratings seem to react too slowly. This replays the
published Elo (`elo_variants.replay`, rookie discount and faster early moves on)
with four designs, each tuned on seasons up to 2021 and reported on 2022 onwards
against the published Elo on the same games:

- **Uniform K** (`K`): every move, league offsets included, scaled together. A
  reference: K 25–30 helped domestic games in team Elo but hurt international ones.
- **K by tier** (`league_factors`): players' moves in major-league games scaled to
  K_major / 20 and in other domestic leagues to K_other / 20; international games
  and every league offset move as today.
- **Time away** (`away_factor`): a player back after time away moves
  1 + a × min(days away / 365, 1) times as much (a Glicko-style uncertainty).
- **K by tier + time away**: K by tier's chosen pair with the time-away grid.

Grids are fixed in advance. Tuning objective, as `elo_new_players.py`: mean Elo
log loss over domestic (major-league) and within-other-league games up to 2021.
Held-out sections (2022 on): domestic and international Elo and FORGE, within other
leagues Elo on per-league curves and FORGE (Elo + Form), and cross-league Elo.

Usage:
    VECLIB_MAXIMUM_THREADS=1 uv run python scripts/research/elo_k_tier.py --out docs/research/elo_k_tier.md
"""

import argparse
import datetime
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import elo_new_players as enp
import elo_variants as ev
import evaluate_metrics as em

from prometheus.types import INTERNATIONAL_LEAGUES

TRAIN_LAST = 2021
K_BASE = ev.K_DEFAULT  # the published K (20)
TIERS = (20, 24, 28, 32)
AWAY = (0.5, 1.0, 2.0)


def tier_factors(leagues, k_major, k_other):
    """`league_factors` for K `k_major` in major leagues and `k_other` in other
    domestic leagues (international events stay at the published K)."""
    out = {}
    for league in leagues:
        if league in INTERNATIONAL_LEAGUES:
            continue
        k = k_major if league in em.MAJORS else k_other
        if k != K_BASE:
            out[league] = k / K_BASE
    return out


def designs(leagues):
    """Each design's grid: (label, replay kwargs) pairs, fixed before any scoring."""
    return {
        "Uniform K": [({"K": k}, {"K": k}) for k in TIERS[1:]],
        "K by tier": [
            (
                {"k_major": m, "k_other": o},
                {"league_factors": tier_factors(leagues, m, o)},
            )
            for m in TIERS
            for o in TIERS
            if (m, o) != (K_BASE, K_BASE)
        ],
        "Time away": [({"away_factor": a}, {"away_factor": a}) for a in AWAY],
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out", type=Path)
    args = ap.parse_args()

    inputs = ev.load_inputs(verbose=False)
    pairs = em.load_pair_games()
    years = sorted(inputs.frame["year"].unique())
    train = [y for y in years if y <= TRAIN_LAST]
    test = [y for y in years if y > TRAIN_LAST]
    leagues = inputs.games["league"].unique()
    margin = ev.game_length_margin()
    base_pre = ev.replay(inputs, margin)

    lines = [
        f"## Elo K by tier ({datetime.date.today().isoformat()})\n",
        "Generated by `scripts/research/elo_k_tier.py`. Tuned on "
        f"{train[0]}–{train[-1]} (objective: mean Elo log loss over domestic and "
        "within-other-league games), reported on "
        f"{test[0]}–{test[-1]}. Δ is variant minus published Elo (K 20, rookie "
        "discount on) log loss (negative is better), paired bootstrap over games.\n",
        "### Tuning\n",
        "| Design | Parameters | Train objective |",
        "|---|---|---:|",
        f"| Published | K 20 | {enp.objective(inputs, pairs, base_pre, train):.5f} |",
    ]
    chosen = {}

    def run(design, grid):
        scored = []
        for label, kw in grid:
            pre = ev.replay(inputs, margin, **kw)
            scored.append((enp.objective(inputs, pairs, pre, train), label, kw))
            print(f"  {design} {label}: {scored[-1][0]:.5f}", flush=True)
            lines.append(f"| {design} | {label} | {scored[-1][0]:.5f} |")
        best = min(scored, key=lambda t: t[0])
        chosen[design] = best[1:]
        return best

    grids = designs(leagues)
    for design, grid in grids.items():
        run(design, grid)
    tier_label, tier_kw = chosen["K by tier"]
    run(
        "K by tier + time away",
        [
            ({**tier_label, "away_factor": a}, {**tier_kw, "away_factor": a})
            for a in AWAY
        ],
    )

    base_scores = ev.score(inputs, base_pre, years=test)
    base_other_g, base_other = enp.other_losses(pairs, base_pre, test)
    base_cross_g, base_cross = enp.cross_losses(pairs, base_pre, test)
    base_of_g, base_of = enp.other_forge_losses(inputs, pairs, base_pre, test)
    lines += [
        "\n### Held out\n",
        "| Design | Elo, domestic | Elo, international | FORGE, domestic "
        "| FORGE, international | Elo, other leagues | FORGE, other leagues "
        "| Elo, cross-league |",
        "|---|---|---|---|---|---|---|---|",
        f"| Published (log loss) | {base_scores.log_loss('elo_live', 'Domestic').mean():.4f} "
        f"| {base_scores.log_loss('elo_live', 'International').mean():.4f} "
        f"| {base_scores.log_loss('forge', 'Domestic').mean():.4f} "
        f"| {base_scores.log_loss('forge', 'International').mean():.4f} "
        f"| {base_other.mean():.4f} | {base_of.mean():.4f} | {base_cross.mean():.4f} |",
    ]
    for design, (label, kw) in chosen.items():
        pre = ev.replay(inputs, margin, **kw)
        s = ev.score(inputs, pre, years=test)
        oth_g, oth = enp.other_losses(pairs, pre, test)
        cr_g, cr = enp.cross_losses(pairs, pre, test)
        of_g, of = enp.other_forge_losses(inputs, pairs, pre, test)
        assert len(oth_g) == len(base_other_g) and len(cr_g) == len(base_cross_g)
        assert len(of_g) == len(base_of_g)
        cells = [
            enp._delta(s.log_loss(m, t), base_scores.log_loss(m, t))
            for m, t in (
                ("elo_live", "Domestic"),
                ("elo_live", "International"),
                ("forge", "Domestic"),
                ("forge", "International"),
            )
        ] + [
            enp._delta(oth, base_other),
            enp._delta(of, base_of),
            enp._delta(cr, base_cross),
        ]
        lines.append(f"| {design} {label} | " + " | ".join(cells) + " |")
    lines.append(
        f"\nGames: domestic {int(base_scores.mask('Domestic').sum()):,}, international "
        f"{int(base_scores.mask('International').sum()):,}, other leagues "
        f"{len(base_other_g):,} (FORGE {len(base_of_g):,}), cross-league "
        f"{len(base_cross_g):,}.\n"
    )
    text = "\n".join(lines) + "\n"
    print(text)
    if args.out:
        args.out.write_text(text)


if __name__ == "__main__":
    main()
