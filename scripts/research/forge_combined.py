"""
forge_combined.py: the 2026-10-12 FORGE changes together, and each one's share.

Three changes passed alone: roster-aware Form (`form_roster.py`), faster moves after
time away (`elo_k_tier.py`) and a bonus for players moving down from a major
(`elo_league_moves_direction.py`). This scores, on the held-out seasons (2022 on),
with nothing retuned:

- the combination against Elo and Form as published before them (`BEFORE`);
- the combination without each change in turn (that change's share, paired
  against the combination);
- the log rookie discount (`elo_experience.py`, 250 over 200 games) added on top.

Sections as in `elo_new_players.py`: Elo and FORGE on domestic and international
games, within other leagues (Elo on per-league curves, FORGE on one curve), and
cross-league Elo. Paired bootstrap over games.

Usage:
    VECLIB_MAXIMUM_THREADS=1 uv run python scripts/research/forge_combined.py --out docs/research/forge_combined.md
"""

import argparse
import datetime
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import elo_new_players as enp
import elo_variants as ev
import evaluate_metrics as em

from prometheus import form

TRAIN_LAST = 2021
# The linear rookie discount published on 2026-10-08 (200 over 50 games); the
# combination is scored with it, and the log discount (now published) on top.
LINEAR_ROOKIE = {"rookie_curve": "linear", "rookie_penalty": 200, "rookie_games": 50}
LOG_ROOKIE = {"rookie_curve": "log", "rookie_penalty": 250, "rookie_games": 200}
# Elo before the three changes, as published on 2026-10-08.
BEFORE = {
    **LINEAR_ROOKIE,
    "away_factor": 0.0,
    "move_down_bonus": 0.0,
    "move_up_penalty": 0.0,
}
SECTIONS = (
    "Elo, domestic",
    "Elo, international",
    "FORGE, domestic",
    "FORGE, international",
    "Elo, other leagues",
    "FORGE, other leagues",
    "Elo, cross-league",
)


def form_states_with(rosters):
    """`ev.variant_form_states` with or without roster-aware Form."""

    def states(inputs, pre_match):
        return form.form_states(
            form.opponent_adjust(
                inputs.form_games, elos=ev.pregame_elos(inputs, pre_match)
            ),
            rosters=inputs.rosters if rosters else None,
        )

    return states


def section_losses(inputs, pairs, years, elo_kw, roster_form):
    """Per-game log loss in every section for one Elo replay and Form choice."""
    ev.variant_form_states = form_states_with(roster_form)
    pre = ev.replay(inputs, ev.game_length_margin(), **elo_kw)
    s = ev.score(inputs, pre, years=years)
    _, other = enp.other_losses(pairs, pre, years)
    _, other_forge = enp.other_forge_losses(inputs, pairs, pre, years)
    _, cross = enp.cross_losses(pairs, pre, years)
    return dict(
        zip(
            SECTIONS,
            (
                s.log_loss("elo_live", "Domestic"),
                s.log_loss("elo_live", "International"),
                s.log_loss("forge", "Domestic"),
                s.log_loss("forge", "International"),
                other,
                other_forge,
                cross,
            ),
        )
    )


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out", type=Path)
    args = ap.parse_args()

    inputs = ev.load_inputs(verbose=False)
    pairs = em.load_pair_games()
    years = sorted(inputs.frame["year"].unique())
    test = [y for y in years if y > TRAIN_LAST]

    runs = {
        "Before": (BEFORE, False),
        "Combined": (LINEAR_ROOKIE, True),
        "Combined without roster Form": (LINEAR_ROOKIE, False),
        "Combined without time away": ({**LINEAR_ROOKIE, "away_factor": 0.0}, True),
        "Combined without the move-down bonus": (
            {**LINEAR_ROOKIE, "move_down_bonus": 0.0},
            True,
        ),
        "Combined + log rookie discount": (LOG_ROOKIE, True),
    }
    losses = {}
    for name, (kw, roster) in runs.items():
        print(f"  {name}", flush=True)
        losses[name] = section_losses(inputs, pairs, test, kw, roster)

    def table(rows, base):
        out = [
            "| Variant | " + " | ".join(SECTIONS) + " |",
            "|---" * (len(SECTIONS) + 1) + "|",
            f"| {base} (log loss) | "
            + " | ".join(f"{losses[base][s].mean():.4f}" for s in SECTIONS)
            + " |",
        ]
        for name in rows:
            out.append(
                f"| {name} | "
                + " | ".join(
                    enp._delta(losses[name][s], losses[base][s]) for s in SECTIONS
                )
                + " |"
            )
        return out

    lines = [
        f"## FORGE changes combined ({datetime.date.today().isoformat()})\n",
        "Generated by `scripts/research/forge_combined.py`. Held out "
        f"{test[0]}–{test[-1]}, nothing retuned. Δ is the variant minus the reference "
        "row's log loss (negative is better), paired bootstrap over games. Curves and "
        "Form weights are fit out of year within the held-out seasons, as in the "
        "other Elo research reports.\n",
        "### The combination against Elo and Form before it\n",
        "Roster-aware Form (every lineup change, power 0.5), time away "
        "(`away_factor` 2.0 over 365 days) and the move-down bonus (25, stored).\n",
        *table(["Combined"], "Before"),
        "\n### Each change's share (the combination without it, against the "
        "combination)\n",
        "A positive Δ means removing the change makes that section worse.\n",
        *table(
            [
                "Combined without roster Form",
                "Combined without time away",
                "Combined without the move-down bonus",
            ],
            "Combined",
        ),
        "\n### Log rookie discount on top (250 over 200 games)\n",
        *table(["Combined + log rookie discount"], "Combined"),
        "\nGames: "
        + ", ".join(
            f"{s.lower()} {len(losses['Before'][s]):,}"
            for s in SECTIONS
            if not s.startswith("FORGE, int")
        )
        + ".\n",
    ]
    text = "\n".join(lines) + "\n"
    print(text)
    if args.out:
        args.out.write_text(text)


if __name__ == "__main__":
    main()
