"""Series-score research. Protocol fixed 2026-10-17 before test scoring.

Reuse draft_walkforward's four features, exact annual fits 2019..Y-1, tests
2021..2026. Group ALL maps using gamelog.add_series, then require complete-draft
current map and rated first map; earlier results include missing-draft maps.
One canonical side per series; p0 is production first-map call held constant.
Primary: map-2+ posterior mean versus constant p0. Fit rho in [0,0.7] by map-2+
conditional log loss on earlier years only, pooled (no tier tuning). Also report
existing major/other rho 0.054/0.127, classified by event league, descriptive:
those constants were fitted through 2024 and are not a clean early-year test.
Draft comparisons: v2 + fixed posterior logit shift versus v2; and draft versus
FORGE refit on maps2+, same games. One exploratory adaptation variant: logistic
on v2's features + posterior logit shift + mean earlier-map canonical draft shift
+ signed fraction of current champions already used anywhere in the series.
Baseline for adaptation has all but the last two features and is refitted on
identical earlier-year maps2+. Prior-map shifts are generated by that fold's
prior-year draft fit, never by a fit on the current test year. Current and prior
picks are known before the current result; no final series score, stopping
length, whole-series fearless label or future-map draft enters a predictor.
Report slices, years and pre-2025, 2000 paired series bootstraps, fixed seed via
draft_walkforward. Repeat-free prefix (no earlier-map reuse) is descriptive,
not a verified ruleset/fearless label. No alternative variants selected after
viewing results. Research only; no metric/runtime/weights changes.
"""

import argparse
import sqlite3
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.optimize import minimize_scalar
from scipy.special import expit

sys.path.insert(0, str(Path(__file__).resolve().parent))
import draft_walkforward as dw

from prometheus import gamelog

ROOT = Path(__file__).resolve().parents[2]


def frozen_games():
    """Reuse the handoff's frozen FORGE calls without rebuilding missing calls."""
    rows = dw.player_features(dw.load_rows())
    games = dw.game_table(rows, dw.synergy(rows))
    games = games[games.year >= dw.FIT_FROM]
    frozen = pd.read_pickle(dw.CACHE / "forge.pkl")
    games = games.merge(frozen, on="gameid", validate="one_to_one")
    games["forge_logit"] = dw._logit(games.p_forge)
    return games


def posterior(p, rho, wins, losses):
    k = 1 / np.maximum(rho, 1e-12) - 1
    return (np.asarray(p) * k + wins) / (k + wins + losses)


def histories(maps, picks):
    """All maps, canonical orientation; capture state BEFORE current-map update."""
    g = gamelog.add_series(maps)
    g = g[g.teamname < g.opp].sort_values(["when", "gameid"], kind="mergesort")
    out = []
    for _, group in g.groupby("series", sort=False):
        wins = losses = 0
        used = set()
        first = group.iloc[0].gameid
        previous = []
        prefix_repeat = False
        for row in group.itertuples():
            own, opp = (
                picks.get((row.gameid, row.teamname), ()),
                picks.get((row.gameid, row.opp), ()),
            )
            complete = len(own) == len(opp) == 5
            reuse = (
                (sum(x in used for x in own) - sum(x in used for x in opp)) / 5
                if complete
                else 0.0
            )
            repeats_now = bool(used.intersection((*own, *opp)))
            out.append(
                {
                    "gameid": row.gameid,
                    "first": first,
                    "canonical": row.teamname,
                    "wins": wins,
                    "losses": losses,
                    "previous": tuple(previous),
                    "reuse": reuse,
                    "repeat_free": not (prefix_repeat or repeats_now),
                    "prefix_complete": complete
                    and all(
                        len(picks.get((gid, team), ())) == 5
                        for gid in previous
                        for team in (row.teamname, row.opp)
                    ),
                }
            )
            wins += int(row.result)
            losses += 1 - int(row.result)
            used.update((*own, *opp))
            prefix_repeat |= repeats_now
            previous.append(row.gameid)
    return pd.DataFrame(out)


def fit_rho(frame):
    def objective(r):
        p = np.clip(posterior(frame.p0, r, frame.wins, frame.losses), 1e-9, 1 - 1e-9)
        return -np.mean(frame.cwon * np.log(p) + (1 - frame.cwon) * np.log1p(-p))

    fitted = minimize_scalar(objective, bounds=(0, 0.7), method="bounded").x
    return 0.0 if objective(0.0) <= objective(fitted) else fitted


def load_histories():
    with sqlite3.connect(f"file:{dw.DB_PATH}?mode=ro", uri=True) as conn:
        maps = pd.read_sql(
            "SELECT a.gameid,a.teamname,b.teamname AS opp,a.date,a.result "
            "FROM matches a JOIN matches b ON a.gameid=b.gameid AND a.teamid!=b.teamid",
            conn,
        )
        picks = pd.read_sql(
            "SELECT m.gameid,m.teamname,p.champion FROM match_players p "
            "JOIN matches m ON p.gameid=m.gameid AND p.teamid=m.teamid "
            "WHERE p.champion IS NOT NULL AND p.champion!=''",
            conn,
        )
    maps["when"] = pd.to_datetime(maps.date)
    keyed = picks.groupby(["gameid", "teamname"]).champion.agg(tuple).to_dict()
    return histories(maps, keyed)


def evaluate(games, history):
    # First-map canonical call must be present; no fill from a later map.
    allg = games.set_index("gameid")
    h = history.merge(games, on="gameid")
    h = h[h["first"].isin(allg.index)].copy()
    h["sign"] = np.where(h.blue.eq(h.canonical), 1.0, -1.0)
    first_blue = h["first"].map(allg.blue)
    first_p = h["first"].map(allg.p_forge)
    h["p0"] = np.where(first_blue.eq(h.canonical), first_p, 1 - first_p)
    h["cwon"] = np.where(h.sign == 1, h.won, 1 - h.won)
    h["constant"] = np.where(h.sign == 1, h.p0, 1 - h.p0)
    outputs, rhos = [], {}
    cols = ["forge_logit", *dw.FEATURES]
    for year in dw.TEST_YEARS:
        train = games[games.year.between(dw.FIT_FROM, year - 1)]
        draft, base = dw._fit(train, cols), dw._fit(train, ["forge_logit"])
        before = h[
            h.year.between(dw.FIT_FROM, year - 1) & ((h.wins + h.losses) > 0)
        ].copy()
        test = h[(h.year == year) & ((h.wins + h.losses) > 0)].copy()
        if test.empty or before.empty:
            continue
        rho = fit_rho(before)
        rhos[year] = rho
        for f in (before, test):
            for name, r in (
                ("posterior", rho),
                ("fixed_rho", np.where(f.league.isin(dw.MAJORS), 0.054, 0.127)),
            ):
                cp = posterior(f.p0, r, f.wins, f.losses)
                f[name] = np.where(f.sign == 1, cp, 1 - cp)
            f["score_shift"] = dw._logit(f.posterior) - dw._logit(f.constant)
            f["draft"] = draft.predict_proba(f[cols].to_numpy())[:, 1]
            f["forge_refit"] = base.predict_proba(f[["forge_logit"]].to_numpy())[:, 1]
            f["draft_score"] = expit(dw._logit(f.draft) + f.score_shift)
        # Fold-frozen draft shift on all past/current maps; targets never fit on test.
        z = pd.Series(
            draft.decision_function(games[cols].to_numpy())
            - base.decision_function(games[["forge_logit"]].to_numpy()),
            index=games.gameid,
        )
        sign = h.set_index("gameid").sign
        canonical_shift = z * sign.reindex(z.index)
        for f in (before, test):
            f["prior_draft"] = [
                np.mean([canonical_shift.get(gid, 0.0) for gid in ids]) * s
                if ids
                else 0.0
                for ids, s in zip(f.previous, f.sign)
            ]
            f["reuse"] = f.reuse * f.sign
        control_cols = [*cols, "score_shift"]
        extra_cols = [*control_cols, "prior_draft", "reuse"]
        test["adapt_control"] = dw._fit(before, control_cols).predict_proba(
            test[control_cols].to_numpy()
        )[:, 1]
        test["adapt"] = dw._fit(before, extra_cols).predict_proba(
            test[extra_cols].to_numpy()
        )[:, 1]
        outputs.append(test)
    return pd.concat(outputs, ignore_index=True), rhos


def report(scored, rhos):
    comparisons = [
        ("posterior", "constant"),
        ("fixed_rho", "constant"),
        ("draft", "forge_refit"),
        ("draft_score", "draft"),
        ("adapt", "adapt_control"),
    ]
    lines = [
        "# Series score and earlier drafts",
        "",
        "Protocol fixed before scoring in `scripts/research/series_score.py`.",
        "One primary posterior; existing rho is descriptive; one exploratory two-feature adaptation candidate. Negative is better.",
        "Series grouping includes maps without draft coverage. p0 freezes the first production call; posterior uses earlier results only.",
        "",
        "| Test year | Training-only rho |",
        "|---|---:|",
    ]
    lines += [f"| {y} | {r:.4f} |" for y, r in rhos.items()]
    slices = list(dw.slices(scored)) + [("before 2025", scored[scored.year < 2025])]
    slices += [(str(y), f) for y, f in scored.groupby("year")]
    slices += [
        ("map 2", scored[(scored.wins + scored.losses) == 1]),
        ("map 3+", scored[(scored.wins + scored.losses) >= 2]),
        (
            "repeat-free complete prefix",
            scored[scored.repeat_free & scored.prefix_complete],
        ),
        (
            "repeated complete prefix",
            scored[~scored.repeat_free & scored.prefix_complete],
        ),
    ]
    for a, b in comparisons:
        lines += [
            "",
            f"## {a} − {b}",
            "",
            "| Slice | Maps | Candidate LL | Control LL | Difference (95%) |",
            "|---|---:|---:|---:|---|",
        ]
        for name, f in slices:
            if len(f) < 30:
                continue
            la, lb, d, lo, hi = dw.paired(f, a, b)
            lines.append(
                f"| {name} | {len(f):,} | {la:.4f} | {lb:.4f} | {dw._ci(d, lo, hi)} |"
            )
    lines += [
        "",
        "## Limits",
        "",
        "First-map production coverage and current-map full drafts required. Missing earlier drafts are zero in exploratory prior-shift means; all earlier map results count. No terminal-score filtering, avoiding conditioning predictors on future outcomes, but incomplete OE series may remain.",
        "Fixed 0.054/0.127 uses event-major status (not home-league status) and constants fitted through 2024: descriptive only. The primary pooled rho always fits earlier years.",
        "Repeat-free prefix is consistent with fearless play but is not proof of rules; no future maps are read for this label. Draft features were selected after 2025–26, so pre-2025 is separately shown. FORGE weights themselves inherit historical fitting limitations.",
        "Adaptation is exploratory; no production changes or tradable-edge claims.",
    ]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out", type=Path, default=ROOT / "docs/research/series_score.md"
    )
    args = parser.parse_args()
    games = frozen_games()
    scored, rhos = evaluate(games, load_histories())
    args.out.write_text(report(scored, rhos))
    print(f"Wrote {args.out}: {len(scored):,} maps")


if __name__ == "__main__":
    main()
